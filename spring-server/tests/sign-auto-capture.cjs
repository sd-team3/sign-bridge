const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../src/main/webapp/resources/js/sign-auto-capture.js'),'utf8'),context);
const {Gate} = context.window.SignAutoCapture;
const gate = new Gate();
assert.equal(gate.update(0,0,'idle'),null);
assert.equal(gate.update(1,100,'idle'),null);
assert.equal(gate.update(1,200,'idle'),null);
assert.equal(gate.update(1,250,'idle'),'start');
assert.equal(gate.update(2,500,'recording'),null);
assert.equal(gate.update(1,800,'recording'),null);
assert.equal(gate.update(0,900,'recording'),null);
assert.equal(gate.update(1,1300,'recording'),null);
assert.equal(gate.update(0,1500,'recording'),null);
assert.equal(gate.update(0,2200,'recording'),null);
assert.equal(gate.update(0,2400,'recording'),'finish');
assert.equal(gate.update(1,2500,'evaluating'),null);
assert.equal(gate.update(1,5000,'result'),null);
assert.equal(gate.update(1,6000,'result'),null);
assert.equal(gate.update(0,6100,'result'),null);
assert.equal(gate.update(0,6700,'result'),null);
assert.equal(gate.update(1,6800,'result'),null);
assert.equal(gate.update(1,6950,'result'),'start');
gate.reset();
assert.equal(gate.update(1,0,'idle',false),null);
assert.equal(gate.update(1,1000,'idle',false),null);
assert.equal(gate.update(1,2000,'error'),null);
assert.equal(gate.update(1,4000,'error'),null);
gate.reset(true);
assert.equal(gate.update(1,100,'idle'),null);
assert.equal(gate.update(1,1000,'idle'),null);
assert.equal(gate.update(0,1100,'idle'),null);
assert.equal(gate.update(0,1700,'idle'),null);
assert.equal(gate.update(1,1800,'idle'),null);
assert.equal(gate.update(1,1950,'idle'),'start');
console.log('AUTO_CAPTURE_GATE_OK: one-hand start, two-hand absence, dropout tolerance, min duration, rearm, busy/error guards');
