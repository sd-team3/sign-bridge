const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const{JSDOM}=require('jsdom');
const dom=new JSDOM('<main><div id="result"></div></main>',{url:'https://test.local',runScripts:'outside-only'});
const w=dom.window;
w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
w.eval(fs.readFileSync(path.join(__dirname,'../src/main/webapp/resources/js/sign-coaching.js'),'utf8'));
const image='data:image/svg+xml;base64,'+Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>').toString('base64');
const frames=['초반','중간','후반'].map((phase,i)=>({phase,image,reference_timestamp_ms:i*1000,user_timestamp_ms:i*1100,
  comparison_status:['no_major_difference','highlighted','unavailable'][i],highlight_notes:i===1?['왼손이 낮게 보여요. 조금 올려 주세요.']:[]}));
const container=w.document.getElementById('result');
const feedback={policy:'semantic_v1',feedback_required:true,reason:'uncertain_recognition',message:'다시 확인해요.',actions:[],reference_notes:['표시되지 않은 오른손 설명'],comparison:{available:true,alignment:'dtw',notice:'참고 비교',frames}};
w.SignCoaching.render(container,feedback);
assert.equal(container.querySelector('.sc-avatar').open,true);
assert.match(container.querySelector('img').alt,/중간/);
assert.match(container.querySelector('.sc-highlight-notes').textContent,/왼손이 낮게/);
assert.doesNotMatch(container.textContent,/표시되지 않은 오른손/);
const buttons=container.querySelectorAll('.sc-avatar-tools button');assert.equal(buttons.length,4);
buttons[0].click();assert.match(container.querySelector('img').alt,/초반/);assert.equal(buttons[0].getAttribute('aria-pressed'),'true');
assert.match(container.querySelector('.sc-highlight-notes').textContent,/동작에서 큰 차이를 찾지 못했어요/);
assert.doesNotMatch(container.querySelector('.sc-highlight-notes').textContent,/왼손이 낮게/);
buttons[2].click();assert.match(container.querySelector('.sc-highlight-notes').textContent,/안내하기 어려워요/);
assert.doesNotMatch(container.querySelector('.sc-highlight-notes').textContent,/큰 차이를 찾지 못/);
buttons[3].click();assert(w.document.querySelector('dialog').open);w.document.querySelector('dialog button').click();assert.equal(w.document.querySelector('dialog'),null);
w.SignCoaching.render(container,{...feedback,feedback_required:false});assert.equal(container.querySelector('.sc-avatar').open,false);
w.SignCoaching.render(container,{...feedback,comparison:{available:false,notice:'이번 비교 불가'}});assert.match(container.textContent,/이번 비교 불가/);assert.equal(container.querySelector('img'),null);
w.SignCoaching.render(container,{...feedback,comparison:{available:true,frames:[{image:'javascript:alert(1)'}]}});assert.equal(container.querySelector('img'),null);
w.SignCoaching.render(container,feedback);container.querySelectorAll('.sc-avatar-tools button')[3].click();assert(w.document.querySelector('dialog'));w.SignCoaching.render(container,{...feedback,message:'다른 시도'});assert.equal(w.document.querySelector('dialog'),null);
w.SignCoaching.render(container,{...feedback,comparison:{...feedback.comparison,frames:[{...frames[1],highlight_notes:['<img src=x onerror=alert(1)>']}]}});
assert.equal(container.querySelector('.sc-highlight-notes img'),null);
assert.match(container.querySelector('.sc-highlight-notes').textContent,/<img src=x/);
console.log('COMPARISON_UI_OK: stage selection, zoom, uncertainty, fallback, image safety');
dom.window.close();
